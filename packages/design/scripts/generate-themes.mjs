// Generates the brand theme stylesheets in src/styles from the ramp specs below.
//
// Skeleton reads its palette from Tailwind `@theme` variables. A theme is a
// `[data-theme='<name>']` block that overrides those variables, so each brand
// is one block of tokens plus its color ramps. Edit the specs here and rerun
// `pnpm --filter @sm-urb/design build:themes`; do not hand-edit the CSS.

import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const here = dirname(fileURLToPath(import.meta.url));
const outDir = join(here, "..", "src", "styles");

// Shade ladder shared by every family, matching Skeleton's 50-950 convention.
const SHADES = [50, 100, 200, 300, 400, 500, 600, 700, 800, 900, 950];
const LIGHTNESS = [0.975, 0.935, 0.88, 0.79, 0.67, 0.55, 0.47, 0.4, 0.33, 0.27, 0.2];
// Chroma rises to the peak at 500 and tapers at both ends, so pale and deep shades stay usable.
const CHROMA_PROFILE = [0.12, 0.25, 0.5, 0.75, 0.92, 1, 0.92, 0.82, 0.66, 0.5, 0.34];

// Optional per-family lift. A highlight hue like chartreuse reads as olive at mid-lightness, so it sits lighter.
function ramp(name, { hue, peak, lift = 0 }) {
  const lines = SHADES.map((shade, i) => {
    const l = Math.min(0.99, LIGHTNESS[i] + lift * (1 - LIGHTNESS[i]));
    const c = (peak * CHROMA_PROFILE[i]).toFixed(3);
    return `\t--color-${name}-${shade}: oklch(${l} ${c} ${hue});`;
  });
  return lines;
}

// Skeleton's contrast rule: dark text on the light half of the ramp, light text on the dark half.
function contrast(name) {
  const lines = [
    `\t--color-${name}-contrast-dark: var(--color-${name}-950);`,
    `\t--color-${name}-contrast-light: var(--color-${name}-50);`,
  ];
  SHADES.forEach((shade, i) => {
    const onLight = LIGHTNESS[i] > 0.6;
    lines.push(`\t--color-${name}-contrast-${shade}: var(--color-${name}-contrast-${onLight ? "dark" : "light"});`);
  });
  return lines;
}

function family(name, spec) {
  return [`\t/* ${spec.label} */`, ...ramp(name, spec), ...contrast(name)];
}

function themeBlock(theme) {
  const body = [
    ...family("primary", theme.primary),
    ...family("secondary", theme.secondary),
    ...family("tertiary", theme.tertiary),
    ...family("surface", theme.surface),
    "",
    "\t/* Brand accent (used by preset-filled-brand and the wordmark) */",
    "\t--color-brand-light: var(--color-primary-500);",
    "\t--color-brand-contrast-light: var(--color-primary-contrast-500);",
    "\t--color-brand-dark: var(--color-primary-400);",
    "\t--color-brand-contrast-dark: var(--color-primary-contrast-400);",
    "",
    "\t/* Page background and text */",
    "\t--color-root-bg-light: var(--color-surface-50);",
    "\t--color-root-bg-dark: var(--color-surface-950);",
    "\t--typo-base--color-light: var(--color-surface-950);",
    "\t--typo-base--color-dark: var(--color-surface-50);",
    "\t--typo-anchor--color-light: var(--color-primary-700);",
    "\t--typo-anchor--color-dark: var(--color-primary-300);",
    "",
    "\t/* Shape and type */",
    `\t--radius-base: ${theme.radius.base};`,
    `\t--radius-container: ${theme.radius.container};`,
    `\t--typo-base--font-family: ${theme.fonts.body};`,
    `\t--typo-heading--font-family: ${theme.fonts.display};`,
    `\t--typo-heading--font-weight: ${theme.headingWeight};`,
    `\t--typo-heading--letter-spacing: ${theme.headingTracking};`,
    "",
    "\t/* Brand-only tokens consumed by base.css */",
    `\t--sm-urb-font-pixel: ${theme.fonts.pixel};`,
    `\t--sm-urb-font-mono: ${theme.fonts.mono};`,
    `\t--sm-urb-shadow-lift: ${theme.shadow};`,
  ];
  return [
    `/* ${theme.title}`,
    `   ${theme.summary}`,
    "   Generated by scripts/generate-themes.mjs. Edit the spec there. */",
    "",
    `[data-theme='${theme.id}'] {`,
    ...body,
    "}",
    "",
  ].join("\n");
}

